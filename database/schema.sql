CREATE DATABASE IF NOT EXISTS sistema_automotivo CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE sistema_automotivo;
CREATE TABLE IF NOT EXISTS marcas (id BIGINT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(80) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS modelos (id BIGINT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(80) NOT NULL,
 marca_id BIGINT NOT NULL, CONSTRAINT fk_modelo_marca FOREIGN KEY (marca_id) REFERENCES marcas(id),
 CONSTRAINT uk_modelo_marca UNIQUE(nome, marca_id));
CREATE TABLE IF NOT EXISTS veiculos (id BIGINT AUTO_INCREMENT PRIMARY KEY, modelo_id BIGINT NOT NULL,
 ano INT NOT NULL, cor VARCHAR(40) NOT NULL, preco DECIMAL(12,2) NOT NULL,
 quilometragem INT NOT NULL, status VARCHAR(20) NOT NULL,
 CONSTRAINT fk_veiculo_modelo FOREIGN KEY (modelo_id) REFERENCES modelos(id));
